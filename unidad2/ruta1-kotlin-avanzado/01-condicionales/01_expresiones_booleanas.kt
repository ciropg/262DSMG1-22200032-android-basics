// Codelab: Cómo escribir condicionales en Kotlin
// Tema: expresiones booleanas con operadores de comparación

fun main() {
    println(1 == 1)   // true  -> igual a
    println(1 < 1)    // false -> menor que
    println(1 > 0)    // true  -> mayor que
    println(1 <= 1)   // true  -> menor o igual que
    println(1 >= 2)   // false -> mayor o igual que
    println(1 != 2)   // true  -> distinto de
}